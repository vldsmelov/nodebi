import { QueryClient, QueryClientProvider } from "@tanstack/react-query";
import { fireEvent, screen, waitFor } from "@testing-library/react";
import { beforeEach, expect, it, vi } from "vitest";
import { render } from "./render";
import { ParameterChoices } from "@/features/dashboard/ParameterOptions";
import { apiRequest } from "@/lib/api";
vi.mock("@/lib/api", () => ({ apiRequest: vi.fn() }));
const definition = { name: "equipment", label: "Equipment", required: false, logical_type: "integer" as const, options: { workflow_id: "flow", node_id: "node", column_id: "id", label_column_id: "name" } };
const response = { revision: 1, values: [1, 2], choices: [{ value: 1, label: "Pump" }, { value: 2, label: "Pump" }], selected: { value: 3, label: "Valve" }, label_column: { logical_type: "string" }, truncated: true };
beforeEach(() => vi.resetAllMocks());
it("keeps identical labels as separate typed IDs and retains an off-page selected label", async () => {
  vi.mocked(apiRequest).mockResolvedValue(response);
  const change = vi.fn();
  render(<QueryClientProvider client={new QueryClient()}><ParameterChoices definition={definition} parameters={{}} value={3} onChange={change} /></QueryClientProvider>);
  await screen.findByRole("option", { name: "Pump (1)" });
  expect(screen.getByRole("option", { name: "Pump (2)" })).toHaveValue("2");
  expect(screen.getByRole("option", { name: "Valve (3)" })).toHaveValue("3");
  fireEvent.change(screen.getByLabelText("Dashboard selection equipment"), { target: { value: "2" } });
  expect(change).toHaveBeenCalledWith(2);
  expect(JSON.parse(vi.mocked(apiRequest).mock.calls[0][1]!.body as string)).toMatchObject({ selected_value: 3, label_column_id: "name" });
});
it("ignores late choices from the previous slice and preserves an unavailable current selection", async () => {
  let finish: (value: unknown) => void = () => {};
  vi.mocked(apiRequest).mockImplementationOnce(() => new Promise(resolve => { finish = resolve; }));
  vi.mocked(apiRequest).mockResolvedValue({ ...response, choices: [{ value: 4, label: "Current" }], selected: null });
  const client = new QueryClient();
  const change = vi.fn();
  const content = (slice: string) => <QueryClientProvider client={client}><ParameterChoices definition={definition} parameters={{ slice }} value={3} onChange={change} /></QueryClientProvider>;
  const view = render(content("old"));
  await waitFor(() => expect(apiRequest).toHaveBeenCalledTimes(1));
  view.rerender(content("new"));
  await screen.findByRole("option", { name: "Current (4)" });
  finish(response);
  await waitFor(() => expect(client.getQueryCache().findAll()[0].state.status).toBe("success"));
  expect(screen.queryByRole("option", { name: "Pump (1)" })).not.toBeInTheDocument();
  expect(screen.getByLabelText("Dashboard selection equipment")).toHaveValue("3");
  expect(screen.getByText(/The selected value is not in the available data/)).toBeVisible();
  expect(change).not.toHaveBeenCalled();
});
