import { showAllOperations } from "./operation-catalog";
import { expect, test } from "@playwright/test";
import { resolve } from "node:path";

const api = process.env.NODEBI_E2E_API ?? "http://127.0.0.1:8000";

test("build dashboard drill-through in the UI and restore URL slices and history", async ({ page, request }) => {
  test.setTimeout(180000);
  const project = await (await request.post(`${api}/api/v1/projects`, { data: { name: "Dashboard navigation acceptance" } })).json();
  try {
    await page.goto(`/projects/${project.id}/data`);
    await page.locator('input[type="file"]').setInputFiles(resolve("../fixtures/excel/sales.xlsx"));
    await expect(page.getByLabel("Worksheet")).toBeVisible();
    await page.goto(`/projects/${project.id}/workflow`);
    await page.getByRole("button", { name: "Create workflow", exact: true }).click();
    await page.getByText("Workflow parameters", { exact: true }).click();
    await page.getByRole("button", { name: "Add parameter", exact: true }).click();
    await page.getByLabel("Parameter name 1").fill("country");
    await page.getByLabel("Parameter default 1").fill("Korea");
    await expect(page.getByText("Saved", { exact: true })).toBeVisible();
    await showAllOperations(page); await page.getByTitle("Add Excel Source").click();
    await expect(page.getByText("Saved", { exact: true })).toBeVisible();
    await showAllOperations(page); await page.getByTitle("Add Table", { exact: true }).click();
    await page.getByLabel("Input input").selectOption({ index: 1 });
    await page.getByLabel("Chart title").fill("All countries");
    await expect(page.getByText("Saved", { exact: true })).toBeVisible();
    await showAllOperations(page); await page.getByTitle("Add Filter", { exact: true }).click();
    await page.getByLabel("Input input").selectOption({ index: 1 });
    await page.getByRole("button", { name: "Add condition", exact: true }).click();
    await page.getByLabel("Filter column 1").selectOption({ label: "country · string" });
    await page.getByLabel("Filter value source 1").selectOption("country");
    await expect(page.getByText("Saved", { exact: true })).toBeVisible();
    await showAllOperations(page); await page.getByTitle("Add Table", { exact: true }).click();
    const filter = page.getByLabel("Input input").locator("option").filter({ hasText: "Filter (" });
    await page.getByLabel("Input input").selectOption((await filter.getAttribute("value"))!);
    await page.getByLabel("Chart title").fill("Selected country");
    await page.getByLabel("Use parameters in title").check();
    await page.getByLabel("Insert title parameter").selectOption("country");
    await page.getByText("Highlight selection", { exact: true }).click();
    await page.getByLabel("Highlight field", { exact: true }).selectOption({ label: "country" });
    await page.getByLabel("Highlight parameter", { exact: true }).selectOption("country");
    await expect(page.getByText("Saved", { exact: true })).toBeVisible();
    await page.goto(`/projects/${project.id}/dashboard`);
    await page.getByRole("button", { name: "Create dashboard", exact: true }).click();
    await page.getByLabel("Dashboard name").fill("Overview");
    await page.getByLabel("Add visualization").selectOption({ label: "All countries" });
    await page.getByRole("button", { name: "Add widget", exact: true }).click();
    await page.getByRole("button", { name: "Save dashboard", exact: true }).click();
    await expect(page.getByText("Saved", { exact: true })).toBeVisible();
    const overviewId = new URL(page.url()).searchParams.get("dashboard")!;
    await page.getByRole("button", { name: "New dashboard", exact: true }).click();
    await expect(page.getByLabel("Dashboard name")).toHaveValue("Sales dashboard");
    await page.getByLabel("Dashboard name").fill("Country detail");
    await page.getByLabel("Add visualization").selectOption({ label: "Selected country {country}" });
    await page.getByRole("button", { name: "Add widget", exact: true }).click();
    await page.getByText("Dashboard settings", { exact: true }).click();
    await page.getByRole("button", { name: "Add dashboard parameter", exact: true }).click();
    await page.getByLabel("Dashboard parameter name 1").fill("selection");
    await page.getByLabel("Dashboard parameter label 1").fill("Country");
    await page.getByLabel("Required parameter", { exact: true }).check();
    await page.getByLabel("Bind workflow parameter 1").selectOption({ index: 1 });
    await page.getByLabel("Choices workflow for selection").selectOption({ index: 1 });
    const choicesNode = page.getByLabel("Choices node for selection").locator("option").filter({ hasText: "Excel Source (" });
    await page.getByLabel("Choices node for selection").selectOption((await choicesNode.getAttribute("value"))!);
    await page.getByLabel("Choices field for selection").selectOption({ label: "country" });
    await page.getByRole("button", { name: "Add navigation link", exact: true }).click();
    await page.getByLabel("Navigation link label 1").fill("Back to overview");
    await page.getByLabel("Destination dashboard").selectOption(overviewId);
    await page.getByRole("button", { name: "Save dashboard", exact: true }).click();
    await expect(page.getByText("Saved", { exact: true })).toBeVisible();
    const detailId = new URL(page.url()).searchParams.get("dashboard")!;
    const detailSaved = await (await request.get(`${api}/api/v1/dashboards/${detailId}`)).json();
    await page.getByLabel("Dashboard", { exact: true }).selectOption(overviewId);
    await page.getByText("Widget navigation", { exact: true }).click();
    await page.getByLabel("Configure widget navigation").selectOption({ label: "All countries" });
    await page.getByLabel("Destination dashboard").selectOption(detailId);
    await page.getByLabel("Navigation value for selection").selectOption({ label: "Field: country" });
    await page.getByRole("button", { name: "Save dashboard", exact: true }).click();
    await expect(page.getByText("Saved", { exact: true })).toBeVisible();
    await page.getByRole("table").getByRole("row").filter({ has: page.getByRole("cell", { name: "Korea", exact: true }) }).first().click();
    await expect(page.getByLabel("Dashboard name")).toHaveValue("Country detail");
    expect(JSON.parse(new URL(page.url()).searchParams.get("parameters")!)).toEqual({ selection: "Korea" });
    await expect(page.getByRole("table")).toContainText("Korea");
    await expect(page.getByRole("heading", { name: "Selected country Korea", exact: true })).toBeVisible();
    await expect(page.getByRole("table").locator('tbody tr[aria-selected="true"]').first()).toBeVisible();
    const slice = await page.getByRole("table").innerText();
    await page.reload();
    await expect(page.getByLabel("Dashboard name")).toHaveValue("Country detail");
    await expect(page.getByLabel("Dashboard selection selection")).toHaveValue(JSON.stringify("Korea"));
    expect(await page.getByRole("table").innerText()).toBe(slice);
    expect((await (await request.get(`${api}/api/v1/dashboards/${detailId}`)).json()).revision).toBe(detailSaved.revision);
    await page.goBack();
    await expect(page.getByLabel("Dashboard name")).toHaveValue("Overview");
    await page.goForward();
    await expect(page.getByLabel("Dashboard name")).toHaveValue("Country detail");
    await page.getByRole("button", { name: "Back to overview", exact: true }).click();
    await expect(page.getByLabel("Dashboard name")).toHaveValue("Overview");
    await page.goto(`/projects/${project.id}/dashboard?dashboard=${detailId}&parameters=${encodeURIComponent('{"selection":12}')}`);
    // The choices query may also report its bound workflow parameter error.
    await expect(page.getByRole("main").getByRole("alert").filter({ hasText: "Parameter 'selection'" })).toContainText("requires string");
    await expect(page.getByRole("table")).toHaveCount(0);
  } finally {
    await request.delete(`${api}/api/v1/projects/${project.id}?confirm=true`);
  }
});
