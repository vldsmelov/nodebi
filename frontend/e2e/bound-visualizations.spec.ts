import { showAllOperations } from "./operation-catalog";
import { expect, test } from "@playwright/test";
import { readFileSync } from "node:fs";
import { resolve } from "node:path";
test.use({ actionTimeout: 15000 });
const api = process.env.NODEBI_E2E_API ?? "http://127.0.0.1:8000";

test("build field Bar Chart and scalar KPI through named UI connections and restore dashboard settings", async ({ page, request }) => {
  test.setTimeout(120000);
  const project = await (await request.post(`${api}/api/v1/projects`, { data: { name: "Typed visualization acceptance" } })).json();
  try {
    expect((await request.post(`${api}/api/v1/projects/${project.id}/sources/excel`, { multipart: { file: { name: "sales.xlsx", mimeType: "application/vnd.openxmlformats-officedocument.spreadsheetml.sheet", buffer: readFileSync(resolve("../fixtures/excel/sales.xlsx")) } } })).ok()).toBe(true);
    await page.goto(`/projects/${project.id}/workflow`);
    await page.getByRole("button", { name: "New field workflow", exact: true }).click();
    const saved = async () => { await expect(page.getByText("Saved", { exact: true })).toBeVisible(); await expect(page.getByText("Updating fields", { exact: true })).toHaveCount(0); };
    const add = async (name: string) => { await showAllOperations(page); await page.getByTitle(`Add ${name}`, { exact: true }).click(); };
    const connect = async (port: string, label: string) => { await page.getByLabel(`Input ${port}`, { exact: true }).selectOption({ label }); await saved(); };
    await add("Excel Source"); await saved();
    await add("Field arithmetic");
    await page.getByLabel("Node label", { exact: true }).fill("Revenue expression");
    await connect("a", "Excel Source / quantity"); await connect("b", "Excel Source / price");
    await add("Append field");
    await page.getByLabel("Output field name", { exact: true }).fill("Revenue");
    await connect("table", "Excel Source / Dataset"); await connect("value", "Revenue expression / Value");
    await add("Filter"); await connect("input", "Append field / Table");
    await page.getByRole("button", { name: "Add condition", exact: true }).click();
    await page.getByLabel("Filter column 1").selectOption({ label: "Revenue · float" });
    await page.getByLabel("Filter operator 1").selectOption("greater_than");
    await page.getByLabel("Filter value 1", { exact: true }).fill("0"); await saved();
    await add("Group By"); await connect("input", "Filter / Dataset");
    await page.getByLabel("country", { exact: true }).check();
    await page.getByRole("button", { name: "Add aggregation", exact: true }).click();
    await page.getByLabel("Aggregate field 1").selectOption({ label: "Revenue" });
    await page.getByLabel("Aggregation 1", { exact: true }).selectOption("sum");
    await page.getByLabel("Aggregate name 1").fill("Total revenue"); await saved();
    await add("Bar Chart · v2");
    await page.getByLabel("Chart title").fill("Revenue by country");
    await connect("table", "Group By / Dataset");
    await connect("category", "Group By / country");
    await connect("value", "Group By / Total revenue");
    await expect(page.getByLabel("Chart category", { exact: true })).toHaveCount(0);
    await page.getByRole("button", { name: "Preview visualization", exact: true }).click();
    await expect(page.getByRole("img", { name: "Revenue by country", exact: true })).toBeVisible();
    await add("Sum field"); await connect("table", "Group By / Dataset"); await connect("value", "Group By / Total revenue");
    await add("KPI · v2"); await page.getByLabel("Chart title").fill("Revenue total");
    await connect("value", "Sum field / Scalar");
    await page.getByRole("button", { name: "Preview visualization", exact: true }).click();
    await expect(page.getByTestId("kpi-value")).toBeVisible();
    const workflowId = new URL(page.url()).searchParams.get("workflow");
    const graphPath = `${api}/api/v1/workflows/${workflowId}`;
    const graph = await (await request.get(graphPath)).json();
    const charts = graph.nodes.filter((node: { version: number }) => node.version === 2);
    expect(charts).toHaveLength(2);
    const bar = charts.find((node: { type: string }) => node.type === "bar_chart");
    const kpi = charts.find((node: { type: string }) => node.type === "kpi");
    const barResult = await (await request.get(`${api}/api/v1/visualizations/${bar.id}/result`)).json();
    const kpiResult = await (await request.get(`${api}/api/v1/visualizations/${kpi.id}/result`)).json();
    expect(kpiResult.rows[0][kpiResult.value_field]).toBeCloseTo(barResult.rows.reduce((sum: number, row: Record<string, number>) => sum + row[barResult.value_field], 0));
    await page.goto(`/projects/${project.id}/dashboard`);
    await page.getByRole("button", { name: "Create dashboard", exact: true }).click();
    for (const title of ["Revenue by country", "Revenue total"]) {
      await page.getByLabel("Add visualization", { exact: true }).selectOption({ label: title });
      await page.getByRole("button", { name: "Add widget", exact: true }).click();
    }
    await page.getByRole("button", { name: "Save dashboard", exact: true }).click();
    await expect(page.getByText("Saved", { exact: true })).toBeVisible();
    const barWidget = page.locator("[data-widget-id]").filter({ has: page.getByRole("img", { name: "Revenue by country", exact: true }) });
    await barWidget.getByRole("button", { name: "Edit visualization", exact: true }).click();
    const dialog = page.getByRole("dialog", { name: "Edit visualization", exact: true });
    await dialog.getByLabel("Orientation").selectOption("horizontal");
    await dialog.getByRole("button", { name: "Save visualization", exact: true }).click();
    await expect(dialog).not.toBeVisible();
    const updated = await (await request.get(graphPath)).json();
    expect(updated.version).toBe(2);
    const ordered = (items: { id: string }[]) => [...items].sort((a, b) => a.id.localeCompare(b.id));
    expect(ordered(updated.edges)).toEqual(ordered(graph.edges));
    expect(updated.presentation).toEqual(graph.presentation);
    await page.reload();
    await expect(page.getByRole("img", { name: "Revenue by country", exact: true })).toBeVisible();
    await expect(page.getByTestId("kpi-value")).toBeVisible();
    expect((await (await request.get(`${api}/api/v1/visualizations/${bar.id}/result`)).json()).orientation).toBe("horizontal");
    await barWidget.getByRole("button", { name: "Independent visualization copy", exact: true }).click();
    const copyDialog = page.getByRole("dialog", { name: "Independent visualization copy", exact: true });
    await copyDialog.getByLabel("Chart title").fill("Independent revenue");
    await expect(copyDialog.getByLabel("Chart value", { exact: true })).toHaveCount(0);
    await copyDialog.getByRole("button", { name: "Create independent copy", exact: true }).click();
    await expect(copyDialog).not.toBeVisible();
    await expect(page.getByRole("img", { name: "Independent revenue", exact: true })).toBeVisible();
    const copied = await (await request.get(graphPath)).json();
    const newChart = copied.nodes.find((node: { config: { title?: string } }) => node.config.title === "Independent revenue");
    expect(newChart.version).toBe(2);
    expect(copied.edges.filter((edge: { target_node_id: string }) => edge.target_node_id === newChart.id)).toHaveLength(3);
    expect((await (await request.get(`${api}/api/v1/visualizations/${bar.id}/result`)).json()).title).toBe("Revenue by country");
    await page.locator("[data-widget-id]").filter({ has: page.getByRole("img", { name: "Independent revenue", exact: true }) }).getByRole("link", { name: "Open calculation", exact: true }).click();
    await expect(page).toHaveURL(/mode=fields/);
    await expect(page.getByLabel("Input category", { exact: true })).toBeVisible();
    const languages = page.getByRole("combobox").filter({ has: page.locator('option[value="tt"]') });
    const themes = page.getByRole("combobox").filter({ has: page.locator('option[value="light"]') });
    await themes.selectOption("light");
    await languages.selectOption("ru");
    await expect(page.getByText("Подключите таблицу, категорию и значение из одного выхода таблицы. Агрегацию выполните перед диаграммой.", { exact: true })).toBeVisible();
    await languages.selectOption("tt");
    await expect(page.getByText("Таблицаны, категорияне һәм кыйммәтне бер таблица чыгышыннан тоташтырыгыз. Агрегацияне диаграмма алдыннан башкарыгыз.", { exact: true })).toBeVisible();
    await languages.selectOption("en");
    await themes.selectOption("dark");
    await page.screenshot({ path: test.info().outputPath("bound-chart-inspector.png") });
  } finally { await request.delete(`${api}/api/v1/projects/${project.id}?confirm=true`); }
});
