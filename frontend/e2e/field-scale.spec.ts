import { expect, test } from "@playwright/test";
import { execFileSync } from "node:child_process";
import { resolve } from "node:path";
const api = process.env.NODEBI_E2E_API ?? "http://127.0.0.1:8000";

test("navigate 168 nodes and virtualize a real 1024-column workbook without eager previews", async ({ page, request }) => {
  test.setTimeout(120000);
  const project = await (await request.post(`${api}/api/v1/projects`, { data: { name: "Field scale acceptance" } })).json();
  try {
    const buffer = execFileSync(resolve("../backend/.venv", process.platform === "win32" ? "Scripts/python.exe" : "bin/python"), ["-c", "import sys; from io import BytesIO; from openpyxl import Workbook; w=Workbook(); s=w.active; s.title='Wide'; s.append([f'field_{i:04d}' for i in range(1024)]); s.append(list(range(1024))); b=BytesIO(); w.save(b); sys.stdout.buffer.write(b.getvalue())"]);
    const uploaded = await request.post(`${api}/api/v1/projects/${project.id}/sources/excel`, { multipart: { file: { name: "wide.xlsx", mimeType: "application/vnd.openxmlformats-officedocument.spreadsheetml.sheet", buffer } } });
    expect(uploaded.ok()).toBe(true); const source = await uploaded.json();
    const workflow = await (await request.post(`${api}/api/v1/projects/${project.id}/workflows`, { data: { name: "168 nodes" } })).json();
    const sourceNode = { id: crypto.randomUUID(), type: "excel_source", version: 1, position: { x: 0, y: 0 }, config: { source_id: source.id, sheet_name: "Wide" }, ui: { label: "Wide source" } };
    const first = await request.put(`${api}/api/v1/workflows/${workflow.id}`, { data: { name: workflow.name, expected_revision: workflow.revision, format_version: 2, nodes: [sourceNode], edges: [] } });
    expect(first.ok()).toBe(true); const saved = await first.json();
    const schema = await (await request.get(`${api}/api/v1/workflows/${workflow.id}/schema`)).json();
    const columns = schema.nodes[0].outputs.dataset.columns;
    expect(columns).toHaveLength(1024);
    const transforms = Array.from({ length: 167 }, (_, index) => ({ id: crypto.randomUUID(), type: "select_columns", version: 1, position: { x: ((index + 1) % 14) * 400, y: Math.floor((index + 1) / 14) * 480 }, config: { column_ids: columns.slice(0, 64).map((column: { column_id: string }) => column.column_id) }, ui: { label: `Branch ${String(index + 1).padStart(3, "0")}` } }));
    const edges = transforms.map(node => ({ id: crypto.randomUUID(), source_node_id: sourceNode.id, source_port: "dataset", target_node_id: node.id, target_port: "input" }));
    const graphResponse = await request.put(`${api}/api/v1/workflows/${workflow.id}`, { data: { name: workflow.name, expected_revision: saved.revision, format_version: 2, nodes: [sourceNode, ...transforms], edges } });
    expect(graphResponse.ok()).toBe(true); const baseline = await graphResponse.json();
    const requests: string[] = [];
    page.on("request", item => { if (item.url().includes(`/workflows/${workflow.id}/`)) requests.push(`${item.method()} ${item.url()}`); });
    const resolved = page.waitForResponse(response => response.url().endsWith(`${workflow.id}/schema`) && response.request().method() === "POST");
    const started = Date.now();
    await page.goto(`/projects/${project.id}/workflow?workflow=${workflow.id}&mode=fields`);
    expect((await (await resolved).json()).valid).toBe(true);
    await expect(page.locator(".react-flow__node")).toHaveCount(168);
    await expect(page.getByText("Updating fields", { exact: true })).toHaveCount(0);
    const metrics = { readyMs: Date.now() - started, handles: await page.locator(".react-flow__handle").count(), elements: await page.locator(".react-flow").locator("*").count(), schemaRequests: requests.filter(url => url.endsWith("/schema")).length };
    console.log("Field scale metrics:", JSON.stringify(metrics));
    await test.info().attach("field-scale.json", { body: JSON.stringify(metrics), contentType: "application/json" });
    expect(metrics.handles).toBeLessThan(500);
    expect(metrics.schemaRequests).toBe(1);
    const navigation = Date.now();
    await page.getByLabel("Find workflow node", { exact: true }).fill("Branch 167");
    await page.getByLabel("Edit workflow node", { exact: true }).selectOption(transforms[166].id);
    await expect(page.locator(`.react-flow__node[data-id="${transforms[166].id}"]`)).toBeInViewport();
    console.log("Field scale navigate ms:", Date.now() - navigation);
    await page.getByLabel("Find workflow node", { exact: true }).fill("Wide source");
    await page.getByLabel("Edit workflow node", { exact: true }).selectOption(sourceNode.id);
    const card = page.locator(`.react-flow__node[data-id="${sourceNode.id}"]`);
    const fields = card.getByLabel("Scrollable fields", { exact: true });
    await expect(fields).toBeVisible();
    await fields.evaluate(element => { element.scrollTop = element.scrollHeight; });
    await expect(card.getByRole("button", { name: "Show connections for field_1023", exact: true })).toBeVisible();
    await card.getByRole("button", { name: "Show connections for field_1023", exact: true }).click();
    await card.getByLabel("Search fields", { exact: true }).fill("field_0001");
    await expect(card.getByRole("button", { name: "Show connections for field_1023", exact: true })).toBeVisible();
    await expect(card.getByRole("button", { name: "Show connections for field_0001", exact: true })).toBeVisible();
    expect(await card.locator(".react-flow__handle").count()).toBeLessThan(25);
    expect(requests.some(url => url.includes("/preview"))).toBe(false);
    const restored = await (await request.get(`${api}/api/v1/workflows/${workflow.id}`)).json();
    expect(restored.revision).toBe(baseline.revision);
    expect(restored.nodes).toHaveLength(168); expect(restored.edges).toHaveLength(167);
  } finally { await request.delete(`${api}/api/v1/projects/${project.id}?confirm=true`); }
});
