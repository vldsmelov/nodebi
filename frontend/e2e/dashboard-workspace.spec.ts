import { expect, test } from "@playwright/test";
import { readFileSync } from "node:fs";
import { resolve } from "node:path";
import { randomUUID } from "node:crypto";
test.use({ actionTimeout: 15000 });
const api = process.env.NODEBI_E2E_API ?? "http://127.0.0.1:8000";

test("author, preview, copy, arrange and recover charts without leaving the dashboard", async ({ page, request, context }) => {
  test.setTimeout(150000);
  const project = await (await request.post(`${api}/api/v1/projects`, { data: { name: "Workspace acceptance" } })).json();
  try {
    const source = await (await request.post(`${api}/api/v1/projects/${project.id}/sources/excel`, { multipart: { file: { name: "sales.xlsx", mimeType: "application/vnd.openxmlformats-officedocument.spreadsheetml.sheet", buffer: readFileSync(resolve("../fixtures/excel/sales.xlsx")) } } })).json();
    const flow = await (await request.post(`${api}/api/v1/projects/${project.id}/workflows`, { data: { name: "Prepared sales" } })).json();
    const node = randomUUID(), pub = randomUUID();
    const graph = await request.put(`${api}/api/v1/workflows/${flow.id}`, { data: { name: flow.name, expected_revision: 1, format_version: 3, nodes: [{ id: node, type: "excel_source", version: 1, position: { x: 0, y: 0 }, config: { source_id: source.id, sheet_name: "Sales" } }], edges: [], result_catalog: { outputs: [{ id: pub, name: "Sales records", node_id: node, port: "dataset", kind: "dataset" }] } } });
    expect(graph.ok()).toBeTruthy();
    await page.goto(`/projects/${project.id}/dashboard`);
    await page.getByRole("button", { name: "Create dashboard", exact: true }).click();
    await page.getByLabel("Dashboard name", { exact: true }).fill("Unsaved dashboard name");
    await page.getByRole("button", { name: "Add chart", exact: true }).click();
    await page.getByRole("button", { name: "Create visualization", exact: true }).click();
    const panel = page.getByRole("complementary", { name: "Visualization settings", exact: true });
    await panel.getByLabel("Visualization name", { exact: true }).fill("Sales table");
    await panel.getByLabel("Visualization type", { exact: true }).selectOption("table");
    await panel.getByRole("button", { name: "Apply visualization", exact: true }).click();
    await expect(panel).toHaveCount(0);
    await expect(page.getByLabel("Dashboard name", { exact: true })).toHaveValue("Unsaved dashboard name");
    const widgetId = await page.locator("[data-widget-id]").first().getAttribute("data-widget-id");
    const widget = page.locator(`[data-widget-id="${widgetId}"]`);
    await expect(widget.locator("table")).toBeVisible();
    const url = page.url();
    await widget.getByLabel("Edit visualization", { exact: true }).click();
    await panel.getByRole("tab", { name: "Appearance", exact: true }).click();
    await expect(widget.getByText("Preview", { exact: true })).toBeVisible();
    await expect(widget.locator("table")).toBeVisible();
    let previews = 0;
    page.on("request", req => { if (req.url().endsWith("/visualizations/preview")) previews++; });
    await panel.getByLabel("Number format", { exact: true }).selectOption("currency");
    await panel.getByLabel("Currency", { exact: true }).fill("RUB");
    await panel.getByLabel("Decimal places", { exact: true }).fill("1");
    await expect(widget.locator("table")).toContainText("RUB");
    await page.waitForTimeout(500);
    expect(previews).toBe(0);
    await panel.getByRole("checkbox", { name: "order_id", exact: true }).uncheck();
    await panel.getByRole("button", { name: "Move column down", exact: true }).first().click();
    await expect(widget.locator("th").first()).toHaveText("country");
    await panel.getByRole("tab", { name: "Placement", exact: true }).click();
    await panel.getByLabel("Widget title", { exact: true }).fill("Local heading");
    await panel.getByRole("button", { name: "Shorter", exact: true }).click();
    await panel.getByRole("button", { name: "Apply visualization", exact: true }).click();
    await expect(panel).toHaveCount(0);
    await page.getByRole("button", { name: "Undo layout change", exact: true }).click();
    await page.getByRole("button", { name: "Redo layout change", exact: true }).click();
    await page.getByRole("button", { name: "Save dashboard", exact: true }).click();
    await expect(page.getByText("Saved", { exact: true })).toBeVisible();

    const boards = (await (await request.get(`${api}/api/v1/projects/${project.id}/dashboards`)).json()).items;
    const board = boards[0], visualId = board.widgets[0].visualization_id;
    await page.getByRole("button", { name: "Add chart", exact: true }).click();
    await page.getByRole("button", { name: "Create visualization", exact: true }).click();
    await panel.getByLabel("Visualization name", { exact: true }).fill("Prepared measures");
    await panel.getByLabel("Chart category", { exact: true }).selectOption({ label: "product" });
    await panel.getByLabel("Chart value", { exact: true }).selectOption({ label: "quantity" });
    await panel.getByRole("button", { name: "Add series", exact: true }).click();
    await panel.getByLabel("Series field 2", { exact: true }).selectOption({ label: "price" });
    await panel.getByLabel("Series name 2", { exact: true }).fill("Unit price");
    await panel.getByRole("tab", { name: "Appearance", exact: true }).click();
    await panel.getByLabel("Orientation", { exact: true }).selectOption("horizontal");
    await panel.getByRole("button", { name: "Apply visualization", exact: true }).click();
    await expect(page.locator("[data-widget-id]")).toHaveCount(2);
    await page.getByRole("button", { name: "Save dashboard", exact: true }).click();
    await expect(page.getByText("Saved", { exact: true })).toBeVisible();
    const second = await (await request.post(`${api}/api/v1/projects/${project.id}/dashboards`, { data: { name: "Shared placement" } })).json();
    expect((await request.put(`${api}/api/v1/dashboards/${second.id}`, { data: { name: second.name, expected_revision: 1, widgets: [{ ...board.widgets[0], id: randomUUID() }] } })).ok()).toBeTruthy();
    await page.getByLabel("Dashboard name", { exact: true }).fill("Keep this draft");
    await widget.getByLabel("Edit visualization", { exact: true }).click();
    await expect(panel.getByText("Shared placement", { exact: true })).toBeVisible();
    await expect(panel.getByRole("button", { name: "Apply visualization", exact: true })).toBeDisabled();
    await panel.getByLabel("Visualization name", { exact: true }).fill("Independent table");
    await panel.getByRole("button", { name: "Independent copy", exact: true }).click();
    await expect(panel).toHaveCount(0);
    await expect(page.getByLabel("Dashboard name", { exact: true })).toHaveValue("Keep this draft");
    await page.getByRole("button", { name: "Save dashboard", exact: true }).click();
    await expect(page.getByText("Saved", { exact: true })).toBeVisible();
    const currentBoard = await (await request.get(`${api}/api/v1/dashboards/${board.id}`)).json();
    expect(currentBoard.widgets.find((item: { id: string }) => item.id === widgetId).visualization_id).not.toBe(visualId);
    expect((await (await request.get(`${api}/api/v1/dashboards/${second.id}`)).json()).widgets[0].visualization_id).toBe(visualId);

    await widget.getByLabel("Edit visualization", { exact: true }).click();
    await panel.getByLabel("Visualization name", { exact: true }).fill("My conflicting draft");
    const other = await context.newPage();
    await other.goto(url);
    await other.locator(`[data-widget-id="${widgetId}"]`).getByLabel("Edit visualization", { exact: true }).click();
    const otherPanel = other.getByRole("complementary", { name: "Visualization settings", exact: true });
    await otherPanel.getByLabel("Visualization name", { exact: true }).fill("Other tab");
    await otherPanel.getByRole("button", { name: "Apply visualization", exact: true }).click();
    await expect(otherPanel).toHaveCount(0); await other.close();
    await panel.getByRole("button", { name: "Apply visualization", exact: true }).click();
    await expect(panel.getByRole("button", { name: "Reload saved settings", exact: true })).toBeVisible();
    await expect(panel.getByLabel("Visualization name", { exact: true })).toHaveValue("My conflicting draft");
    await panel.getByLabel("Close settings", { exact: true }).click();
    await panel.getByRole("button", { name: "Continue editing", exact: true }).click();
    await panel.getByLabel("Close settings", { exact: true }).click();
    await panel.getByRole("button", { name: "Discard changes", exact: true }).click();
    await page.reload();
    await expect(page.getByLabel("Dashboard name", { exact: true })).toHaveValue("Keep this draft");
    await expect(widget.locator("table")).toBeVisible();
    expect(page.url()).toBe(url);

    for (const locale of ["ru", "tt", "en"]) {
      await page.locator('select').filter({ has: page.locator('option[value="ru"]') }).selectOption(locale);
      for (const theme of ["light", "dark"]) {
        await page.locator('select').filter({ has: page.locator('option[value="dark"]') }).selectOption(theme);
        await widget.locator('button').first().click();
        await expect(page.locator('aside')).toBeVisible();
        await expect(widget.locator("table")).toBeVisible();
        const widgetBox = (await widget.boundingBox())!, panelBox = (await page.locator("aside").boundingBox())!;
        expect(widgetBox.x + widgetBox.width).toBeLessThanOrEqual(panelBox.x);
        await page.screenshot({ path: test.info().outputPath(`${locale}-${theme}.png`), fullPage: true });
        await page.keyboard.press("Escape");
        await expect(page.locator('aside')).toHaveCount(0);
      }
    }
    await page.setViewportSize({ width: 700, height: 900 });
    await widget.getByLabel("Edit visualization", { exact: true }).focus();
    await page.keyboard.press("Enter"); await expect(panel).toBeVisible();
    await page.keyboard.press("Escape"); await expect(panel).toHaveCount(0);
  } finally { await request.delete(`${api}/api/v1/projects/${project.id}?confirm=true`); }
});
