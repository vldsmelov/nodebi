import { expect, test } from "@playwright/test";
import { readFileSync } from "node:fs";
import { randomUUID } from "node:crypto";
const api = "http://127.0.0.1:8000";
test.use({ actionTimeout: 15000 });

test("guide a first-time author from workbook to a valid visualization", async ({ page, request }) => {
  test.setTimeout(90000);
  const project = await (await request.post(`${api}/api/v1/projects`, { data: { name: "Usability audit" } })).json();
  try {
    await page.goto(`/projects/${project.id}`);
    await page.getByRole("link", { name: /1\. Data/ }).click();
    const upload = page.getByRole("button", { name: "Upload workbook", exact: true });
    await upload.focus();
    await expect(upload).toBeFocused();
    const chooser = page.waitForEvent("filechooser");
    await page.keyboard.press("Enter");
    await (await chooser).setFiles({ name: "sales.xlsx", mimeType: "application/vnd.openxmlformats-officedocument.spreadsheetml.sheet", buffer: readFileSync("../fixtures/excel/sales.xlsx") });
    await expect(page.getByRole("table")).toBeVisible();
    await expect(page.getByRole("link", { name: "Continue to calculations" })).toBeVisible();
    const remove = page.getByRole("button", { name: "Delete sales" });
    await remove.focus();
    await expect(remove).toBeFocused();
    page.once("dialog", dialog => dialog.dismiss());
    await page.keyboard.press("Enter");
    await expect(page.getByRole("table")).toBeVisible();
    const source = (await (await request.get(`${api}/api/v1/projects/${project.id}/sources`)).json()).items[0];
    const flow = await (await request.post(`${api}/api/v1/projects/${project.id}/workflows`, { data: { name: "Sales" } })).json();
    const node = randomUUID();
    expect((await request.put(`${api}/api/v1/workflows/${flow.id}`, { data: { name: "Sales", expected_revision: 1, format_version: 3, nodes: [{ id: node, type: "excel_source", version: 1, position: { x: 0, y: 0 }, config: { source_id: source.id, sheet_name: "Sales" } }], edges: [], result_catalog: { outputs: [{ id: randomUUID(), name: "Sales records", node_id: node, port: "dataset", kind: "dataset" }] } } })).ok()).toBeTruthy();
    await page.goto(`/projects/${project.id}/dashboard`);
    await page.getByRole("button", { name: "Create dashboard", exact: true }).click();
    await page.getByRole("button", { name: "Add chart", exact: true }).first().click();
    await page.getByRole("button", { name: "Create visualization", exact: true }).click();
    const panel = page.getByRole("complementary", { name: "Visualization settings" });
    let previews = 0;
    page.on("request", req => { if (req.url().endsWith("/visualizations/preview")) previews++; });
    await panel.getByLabel("Visualization name", { exact: true }).fill("My first chart");
    await expect(panel.getByLabel("Chart value", { exact: true })).toBeVisible();
    await page.waitForTimeout(650);
    expect(previews).toBe(0);
    await expect(panel.getByRole("button", { name: "Apply visualization" })).toBeDisabled();
    await expect(panel.getByRole("alert")).toHaveCount(0);
    await panel.getByLabel("Chart category", { exact: true }).selectOption({ label: "product" });
    await panel.getByLabel("Chart value", { exact: true }).selectOption({ label: "quantity" });
    await expect(panel.getByRole("img")).toBeVisible();
    await panel.getByRole("tab", { name: "Data", exact: true }).focus();
    await page.keyboard.press("ArrowRight");
    await expect(panel.getByRole("tab", { name: "Appearance", exact: true })).toBeFocused();
    await expect(panel.getByRole("tab", { name: "Appearance", exact: true })).toHaveAttribute("aria-selected", "true");
    await panel.getByRole("button", { name: "Apply visualization" }).click();
    await page.getByRole("button", { name: "Save dashboard", exact: true }).click();
    await expect(page.getByText("Saved", { exact: true })).toBeVisible();
    await page.getByRole("button", { name: "Add chart", exact: true }).click();
    await page.getByRole("textbox", { name: "Search visualizations" }).fill("not-a-chart");
    await expect(page.getByText("No matching visualizations.", { exact: true })).toBeVisible();
    await page.getByRole("button", { name: "Clear search" }).click();
    await expect(page.getByRole("button", { name: "Add widget", exact: true })).toBeVisible();
  } finally { await request.delete(`${api}/api/v1/projects/${project.id}?confirm=true`); }
});
