import { test, expect, request as createRequest } from "@playwright/test";
import { expectTooltipContrast } from "./tooltip-contrast";
import { activateByKeyboard } from "./keyboard-navigation";
import { observeChartLabels, expectOpaqueChartLabels } from "./chart-label-ink";
const api = process.env.NODEBI_EVOLUTION_API ?? "http://localhost:8010";

for (const kind of ["treemap_chart", "sunburst_chart"]) test(`${kind} preserves exact tree and keyboard group exploration after reload`, async ({ page, request }, testInfo) => {
  test.setTimeout(120_000);
  await observeChartLabels(page, ["A", "B", "C"]);
  const project = await (await request.post(`${api}/api/v1/projects`, { data: { name: "Hierarchy acceptance" } })).json();
  try {
    const measureName = "Total_Regional_Manufacturing_Operations_Division_001";
    const csv = "region,branch,amount\nNorth,A,40\nNorth,B,20\nSouth,C,30\nSouth,D,10\nSouth,Zero,0\n";
    const source = await (await request.post(`${api}/api/v1/projects/${project.id}/imports`, { multipart: { connector: "csv", file: { name: "tree.csv", mimeType: "text/csv", buffer: Buffer.from(csv) } } })).json();
    const { profile } = await (await request.post(`${api}/api/v1/imports/${source.id}/inspect`, { data: { resource_id: "table" } })).json();
    const snapshot = await (await request.post(`${api}/api/v1/imports/${source.id}/apply`, { data: { profile, expected_revision: 1, request_id: crypto.randomUUID() } })).json();
    const created = await request.post(`${api}/api/v1/projects/${project.id}/report-builder/apply`, { data: { request_id: crypto.randomUUID(), source_id: source.id, resource_id: "table", expected_snapshot_id: snapshot.id, name: "Regional hierarchy", dimensions: [profile.fields[0].field_id], measures: [{ name: "Amount", operation: "sum", column_id: profile.fields[2].field_id }] } });
    expect(created.ok()).toBeTruthy();
    const ids = await created.json(), url = `${api}/api/v1/workflows/${ids.workflow_id}`;
    const graph = await (await request.get(url)).json();
    const sourceNode = graph.nodes.find((n: { type: string }) => n.type === "dataset_source");
    const rollup = { id: crypto.randomUUID(), type: "table_rollup", version: 1, position: { x: 400, y: 300 }, config: { dimensions: profile.fields.slice(0, 2).map((f: { field_id: string }) => f.field_id), measures: ["sum", "average"].map((operation, i) => ({ output_id: crypto.randomUUID(), name: [measureName, "Mean"][i], operation, column_id: profile.fields[2].field_id })) } };
    graph.nodes.push(rollup);
    graph.edges.push({ id: crypto.randomUUID(), source_node_id: sourceNode.id, source_port: "dataset", target_node_id: rollup.id, target_port: "input" });
    graph.result_catalog.outputs[0].node_id = rollup.id;
    expect((await request.put(url, { data: { name: graph.name, nodes: graph.nodes, edges: graph.edges, parameters: graph.parameters, presentation: graph.presentation, result_catalog: graph.result_catalog, format_version: 3, expected_revision: graph.revision } })).ok()).toBeTruthy();
    await page.goto(`/projects/${project.id}/dashboard`);
    await page.getByRole("button", { name: "Edit visualization", exact: true }).click();
    await page.getByRole("combobox", { name: "Visualization type", exact: true }).selectOption(kind);
    await expect(page.getByLabel("Hierarchy area measure")).toBeVisible();
    await expect(page.getByLabel("Hierarchy area measure")).toHaveValue(`roll_${rollup.id.replaceAll("-", "")}_measure_${rollup.config.measures[0].output_id.replaceAll("-", "")}`);
    await expect(page.getByLabel("Hierarchy area measure").getByRole("option", { name: "Mean", exact: true })).toHaveCount(0);
    await page.getByRole("tab", { name: "Appearance", exact: true }).click();
    await page.getByLabel("Show labels", { exact: true }).check();
    await page.getByRole("button", { name: "Apply visualization", exact: true }).click();
    const chart = page.getByRole("img", { name: "Regional hierarchy", exact: true });
    await expect(chart.locator("canvas").first()).toBeVisible();
    await page.screenshot({ path: testInfo.outputPath("hierarchy-light.png"), animations: "disabled" });
    await page.reload();
    await expect(chart.locator("canvas").first()).toBeVisible();
    await activateByKeyboard(page, page.getByRole("button", { name: "Data table", exact: true }));
    await expect(page.getByRole("rowheader", { name: "North", exact: true })).toBeVisible();
    await activateByKeyboard(page, page.getByRole("row", { name: /South/ }).getByRole("button", { name: "Open group", exact: true }));
    await expect(page.getByRole("rowheader", { name: "Zero", exact: true })).toBeVisible();
    await expect(page.getByRole("cell", { name: "0.3", exact: true })).toBeVisible();
    await activateByKeyboard(page, page.getByRole("button", { name: "Chart", exact: true }));
    await expect(chart.locator("canvas").first()).toBeVisible();
    await activateByKeyboard(page, page.getByRole("button", { name: "Parent group", exact: true }));
    await expect(page.getByRole("button", { name: "Parent group", exact: true })).toBeDisabled();
    const result = await (await request.post(`${api}/api/v1/visualizations/${ids.visualization_id}/result`, { data: { offset: 5, limit: 1 } })).json();
    expect(result.hierarchy.total).toBe("100");
    expect(result.rows).toHaveLength(8);
    await page.context().addCookies([{ name: "nodebi-theme", value: "dark", domain: new URL(page.url()).hostname, path: "/" }]);
    await page.setViewportSize({ width: 700, height: 1000 });
    await page.reload();
    await expect(chart.locator("canvas").first()).toBeVisible();
    await page.screenshot({ path: testInfo.outputPath("hierarchy-dark-narrow.png"), animations: "disabled" });
    await activateByKeyboard(page, page.getByRole("button", { name: "Data table", exact: true }));
    await activateByKeyboard(page, page.getByRole("row", { name: /South/ }).getByRole("button", { name: "Open group", exact: true }));
    await expect(page.getByRole("rowheader", { name: "Zero", exact: true })).toBeVisible();
    await expect(page.getByRole("cell", { name: "0.3", exact: true })).toBeVisible();
    await activateByKeyboard(page, page.getByRole("button", { name: "Parent group", exact: true }));
    await expect(page.getByRole("rowheader", { name: "North", exact: true })).toBeVisible();
    await activateByKeyboard(page, page.getByRole("button", { name: "Chart", exact: true }));
    await page.setViewportSize({ width: 420, height: 1000 });
    for (const theme of ["light", "dark"]) {
      await page.getByRole("combobox", { name: "Theme", exact: true }).selectOption(theme);
      await chart.scrollIntoViewIfNeeded();
      const canvas = chart.locator("canvas").first(), box = (await canvas.boundingBox())!;
      await expect.poll(() => canvas.evaluate(e => (e as HTMLCanvasElement).width / devicePixelRatio)).toBeCloseTo(box.width, 0);
      await page.evaluate(() => { (window as typeof window & { chartLabelInk?: unknown[] }).chartLabelInk = []; });
      await page.mouse.move(box.x + box.width / 2 + Math.min(box.width, box.height) * 0.3, box.y + box.height / 2);
      await page.screenshot({ path: testInfo.outputPath(`hierarchy-tooltip-${theme}.png`), animations: "disabled" });
      const tooltip = page.getByRole("tooltip");
      await expect(tooltip).toBeVisible();
      await expect(tooltip).toContainText(measureName);
      await expect(tooltip).toContainText("Share of complete total:");
      await expectOpaqueChartLabels(page, ["A", "B", "C"], theme);
      const text = await tooltip.innerText();
      const amount = Number(text.split(`${measureName}: `)[1].split("\n")[0]);
      const share = Number(text.split("Share of complete total: ")[1]);
      expect([10, 20, 30, 40, 60]).toContain(amount);
      expect(share).toBe(amount / 100);
      await expectTooltipContrast(tooltip);
      const bounds = (await tooltip.boundingBox())!;
      expect(bounds.x).toBeGreaterThanOrEqual(0);
      expect(bounds.x + bounds.width).toBeLessThanOrEqual(420);
      expect(bounds.y).toBeGreaterThanOrEqual(0);
      expect(bounds.y + bounds.height).toBeLessThanOrEqual(1000);
      await page.mouse.move(0, 0);
    }
  } finally {
    const cleanup = await createRequest.newContext();
    expect((await cleanup.delete(`${api}/api/v1/projects/${project.id}?confirm=true`)).ok()).toBeTruthy();
    await cleanup.dispose();
  }
});
