import { test, expect, request as createRequest } from "@playwright/test";
import { expectTooltipContrast } from "./tooltip-contrast";
import { activateByKeyboard, tabTo } from "./keyboard-navigation";
const api = process.env.NODEBI_EVOLUTION_API ?? "http://localhost:8010";

for (const zero of [false, true]) test(`funnel ${zero ? "zero population" : "ordered stages"} keeps exact transitions after reload`, async ({ page, request }, testInfo) => {
  test.setTimeout(120_000);
  const project = await (await request.post(`${api}/api/v1/projects`, { data: { name: "Funnel acceptance" } })).json();
  try {
    const count = zero ? 3 : 12;
    const longStage = "Qualified_Regional_Manufacturing_Operations_Division_002";
    const csv = "stage,value,order\n" + Array.from({ length: count }, (_, i) => `${i === 1 ? longStage : `Stage ${String(i + 1).padStart(2, "0")}`},${zero ? 0 : (count - i) * 10},${i + 1}\n`).reverse().join("");
    const source = await (await request.post(`${api}/api/v1/projects/${project.id}/imports`, { multipart: { connector: "csv", file: { name: "stages.csv", mimeType: "text/csv", buffer: Buffer.from(csv) } } })).json();
    const { profile } = await (await request.post(`${api}/api/v1/imports/${source.id}/inspect`, { data: { resource_id: "table" } })).json();
    const snapshot = await (await request.post(`${api}/api/v1/imports/${source.id}/apply`, { data: { profile, expected_revision: 1, request_id: crypto.randomUUID() } })).json();
    const created = await request.post(`${api}/api/v1/projects/${project.id}/report-builder/apply`, { data: { request_id: crypto.randomUUID(), source_id: source.id, resource_id: "table", expected_snapshot_id: snapshot.id, name: "Funnel analysis", dimensions: [profile.fields[0].field_id], measures: [{ name: "Amount", operation: "sum", column_id: profile.fields[1].field_id }] } });
    expect(created.ok()).toBeTruthy();
    const ids = await created.json(), url = `${api}/api/v1/workflows/${ids.workflow_id}`;
    const graph = await (await request.get(url)).json();
    const upstream = graph.nodes.find((n: { type: string }) => n.type === "dataset_source");
    const node = { id: crypto.randomUUID(), type: "funnel_steps", version: 1, position: { x: 400, y: 300 }, config: {} };
    graph.nodes.push(node);
    graph.edges.push({ id: crypto.randomUUID(), source_node_id: upstream.id, source_port: "dataset", target_node_id: node.id, target_port: "input" });
    graph.result_catalog.outputs[0].node_id = node.id;
    expect((await request.put(url, { data: { name: graph.name, nodes: graph.nodes, edges: graph.edges, parameters: graph.parameters, presentation: graph.presentation, result_catalog: graph.result_catalog, format_version: 3, expected_revision: graph.revision } })).ok()).toBeTruthy();
    await page.goto(`/projects/${project.id}/workflow?workflow=${ids.workflow_id}&node=${node.id}`);
    await page.getByLabel("Funnel stage", { exact: true }).selectOption(profile.fields[0].field_id);
    await page.getByLabel("Stage value", { exact: true }).selectOption(profile.fields[1].field_id);
    await page.getByLabel("Stage order", { exact: true }).selectOption(profile.fields[2].field_id);
    await expect.poll(async () => (await (await request.get(url)).json()).nodes.find((n: { id: string }) => n.id === node.id).config).toEqual({ stage_column_id: profile.fields[0].field_id, value_column_id: profile.fields[1].field_id, order_column_id: profile.fields[2].field_id });
    await page.reload();
    await expect(page.getByLabel("Stage order", { exact: true })).toHaveValue(profile.fields[2].field_id);
    await page.getByRole("button", { name: "Preview output", exact: true }).click();
    await expect(page.getByRole("cell", { name: "Stage 01", exact: true })).toBeVisible();
    await page.goto(`/projects/${project.id}/dashboard`);
    await page.getByRole("button", { name: "Edit visualization", exact: true }).click();
    await page.getByRole("combobox", { name: "Visualization type", exact: true }).selectOption("funnel_chart");
    await page.getByRole("tab", { name: "Appearance", exact: true }).click();
    await page.getByLabel("Show labels", { exact: true }).check();
    await page.getByRole("button", { name: "Apply visualization", exact: true }).click();
    const chart = page.getByRole("img", { name: "Funnel analysis", exact: true });
    await expect(chart.locator("canvas").first()).toBeVisible();
    await page.reload();
    await expect(chart.locator("canvas").first()).toBeVisible();
    await expect(page.getByText(`Overall retention (%): ${zero ? "Undefined" : "8.333333333333"}`, { exact: true })).toBeVisible();
    const scroller = page.getByLabel("Funnel chart stages", { exact: true });
    await tabTo(page, scroller);
    await page.keyboard.press("End");
    await expect.poll(() => scroller.evaluate(e => Math.abs(e.scrollHeight - e.clientHeight - e.scrollTop))).toBeLessThan(2);
    await scroller.evaluate(e => { e.scrollTop = 0; });
    await expect.poll(() => scroller.evaluate(e => e.scrollTop)).toBe(0);
    await page.screenshot({ path: testInfo.outputPath("funnel-light.png"), animations: "disabled" });
    await activateByKeyboard(page, page.getByRole("button", { name: "Data table", exact: true }));
    await expect(page.getByRole("rowheader", { name: "Stage 01", exact: true })).toBeVisible();
    if (!zero) await expect(page.getByRole("cell", { name: "1/12", exact: true })).toBeVisible();
    const result = await (await request.post(`${api}/api/v1/visualizations/${ids.visualization_id}/result`, { data: { offset: count - 1, limit: 1 } })).json();
    expect(result.rows).toHaveLength(count);
    expect(result.funnel.points[0].width).toBe(zero ? 0 : 1);
    expect(result.rows.at(-1).previous_exact).toBe(zero ? null : "0.5");
    await activateByKeyboard(page, page.getByRole("button", { name: "Chart", exact: true }));
    await page.context().addCookies([{ name: "nodebi-theme", value: "dark", domain: new URL(page.url()).hostname, path: "/" }]);
    await page.setViewportSize({ width: 420, height: 900 });
    await page.reload();
    await expect(chart.locator("canvas").first()).toBeVisible();
    await expect.poll(() => chart.evaluate(e => Math.abs(e.querySelector("canvas")!.getBoundingClientRect().width - e.clientWidth))).toBeLessThan(2);
    await page.evaluate(() => new Promise<void>(resolve => requestAnimationFrame(() => requestAnimationFrame(() => resolve()))));
    await page.screenshot({ path: testInfo.outputPath("funnel-dark-narrow.png"), animations: "disabled" });
    if (!zero) for (const theme of ["light", "dark"]) {
      await page.getByRole("combobox", { name: "Theme", exact: true }).selectOption(theme);
      await scroller.scrollIntoViewIfNeeded();
      await scroller.evaluate(e => { e.scrollTop = 64; });
      const canvas = chart.locator("canvas").first();
      const box = (await canvas.boundingBox())!;
      await expect.poll(() => canvas.evaluate(e => (e as HTMLCanvasElement).width / devicePixelRatio)).toBeCloseTo(box.width, 0);
      await page.mouse.move(box.x + 105 + (box.width - 129) / 2, box.y + 18 + (box.height - 28) * 1.5 / count);
      await page.screenshot({ path: testInfo.outputPath(`funnel-tooltip-${theme}.png`), animations: "disabled" });
      const tooltip = page.getByRole("tooltip");
      await expect(tooltip).toBeVisible();
      await expect(tooltip).toContainText(longStage);
      await expect(tooltip).toContainText("Previous-stage retention (%): 91.666666666667");
      await expect(tooltip).toContainText("Initial-stage retention (%): 91.666666666667");
      await expect(tooltip).toContainText("Loss from previous stage: 10");
      await expectTooltipContrast(tooltip);
      const bounds = (await tooltip.boundingBox())!;
      expect(bounds.x).toBeGreaterThanOrEqual(0);
      expect(bounds.x + bounds.width).toBeLessThanOrEqual(420);
      expect(bounds.y).toBeGreaterThanOrEqual(0);
      expect(bounds.y + bounds.height).toBeLessThanOrEqual(900);
      await page.mouse.move(0, 0);
    }
  } finally {
    const cleanup = await createRequest.newContext();
    expect((await cleanup.delete(`${api}/api/v1/projects/${project.id}?confirm=true`)).ok()).toBeTruthy();
    await cleanup.dispose();
  }
});
