import { test, expect, request as createRequest } from "@playwright/test";
import { configureFormLayout, expectFormFits, formLayouts } from "./form-reflow";
const api = process.env.NODEBI_EVOLUTION_API ?? "http://localhost:8010";
test.use({ actionTimeout: 10_000 });

for (const layout of formLayouts) test(`guided waterfall requires order, reconciles totals and restores editable graph settings (${layout})`, async ({ page, request }, testInfo) => {
  test.setTimeout(120_000);
  await configureFormLayout(page, layout);
  page.on("dialog", dialog => dialog.accept());
  const project = await (await request.post(`${api}/api/v1/projects`, { data: { name: "Guided waterfall" } })).json();
  const root = `${api}/api/v1/projects/${project.id}`;
  try {
    const source = await (await request.post(`${root}/imports`, { multipart: { connector: "csv", file: { name: "Bridge.csv", mimeType: "text/csv", buffer: Buffer.from("label,amount,kind,sequence\nTax,-2.30,change,3\nStart,10.10,initial,1\nRevenue,0.20,change,2\nEnd,8.00,total,4\n") } } })).json();
    const { profile } = await (await request.post(`${api}/api/v1/imports/${source.id}/inspect`, { data: { resource_id: "table" } })).json();
    const snapshot = await (await request.post(`${api}/api/v1/imports/${source.id}/apply`, { data: { profile, expected_revision: 1, request_id: crypto.randomUUID() } })).json();
    const [label, value, kind, order] = profile.fields.map((f: { field_id: string }) => f.field_id);
    await page.goto(`/projects/${project.id}/build?statistics=1`);
    await page.getByLabel("Report name", { exact: true }).fill("Profit bridge");
    await page.getByRole("combobox", { name: "Prepared dataset", exact: true }).selectOption(snapshot.id);
    await page.getByRole("combobox", { name: "Analysis type", exact: true }).selectOption("waterfall_steps");
    await page.getByLabel("Waterfall step label", { exact: true }).selectOption(label);
    await page.getByLabel("Waterfall value", { exact: true }).selectOption(value);
    await page.getByLabel("Waterfall row type", { exact: true }).selectOption(kind);
    await expect(page.getByRole("button", { name: "Preview calculation", exact: true })).toBeDisabled();
    await page.getByLabel("Waterfall step order", { exact: true }).selectOption("input");
    await page.getByRole("button", { name: "Preview calculation", exact: true }).click();
    await expect(page.getByRole("alert", { name: "Report check failed" })).toBeVisible();
    await expectFormFits(page);
    await expect(page.getByRole("button", { name: "Save report", exact: true })).toBeDisabled();
    await page.getByLabel("Waterfall step order", { exact: true }).selectOption(`field:${order}`);
    await page.reload();
    await page.getByRole("button", { name: "Restore local draft", exact: true }).click();
    await expect(page.getByLabel("Waterfall step order", { exact: true })).toHaveValue(`field:${order}`);
    await page.getByRole("button", { name: "Preview calculation", exact: true }).click();
    await expect(page.getByRole("img", { name: "Profit bridge", exact: true }).locator("canvas")).toBeVisible();
    expect((await (await request.get(`${root}/workflows`)).json()).items).toHaveLength(0);
    await page.getByRole("button", { name: "Step table", exact: true }).click();
    await expect(page.getByRole("row").filter({ has: page.getByRole("cell", { name: "Revenue", exact: true }) })).toContainText("10.30");
    await page.getByRole("button", { name: "Chart", exact: true }).click();
    await page.screenshot({ path: testInfo.outputPath("waterfall-wizard.png"), fullPage: true, animations: "disabled" });
    if (layout === "desktop") await page.setViewportSize({ width: 760, height: 1000 });
    await page.getByRole("combobox", { name: "Theme", exact: true }).selectOption("dark");
    await expect.poll(() => page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
    await page.screenshot({ path: testInfo.outputPath("waterfall-wizard-narrow-dark.png"), fullPage: true, animations: "disabled" });
    if (layout === "desktop") await page.setViewportSize({ width: 1600, height: 1000 });
    await page.getByRole("combobox", { name: "Theme", exact: true }).selectOption("light");
    await page.getByRole("button", { name: "Save report", exact: true }).click();
    await page.getByRole("link", { name: "Open report", exact: true }).click();
    await expect(page).toHaveURL(/\/dashboard\?/);
    await page.reload();
    await page.getByLabel("Widget actions", { exact: true }).click();
    await page.getByRole("link", { name: "Edit in report wizard", exact: true }).click();
    await expect(page.getByLabel("Waterfall step order", { exact: true })).toHaveValue(`field:${order}`);
    await page.getByText("Filters before statistics", { exact: false }).click();
    await page.getByRole("button", { name: "Add filter", exact: true }).click();
    await page.getByRole("combobox", { name: "Field", exact: true }).selectOption(label);
    await page.getByRole("combobox", { name: "Condition", exact: true }).selectOption("not_equals");
    await page.getByLabel("Value", { exact: true }).fill("End");
    await page.getByLabel("Append a final total", { exact: true }).check();
    await page.getByLabel("Final total label", { exact: true }).fill("Forecast");
    await expectFormFits(page);
    await page.getByRole("button", { name: "Preview calculation", exact: true }).click();
    await expect(page.getByRole("button", { name: "Save report", exact: true })).toBeEnabled();
    await page.getByRole("button", { name: "Save report", exact: true }).click();
    await page.getByRole("link", { name: "Open report", exact: true }).click();
    await expect(page).toHaveURL(/\/dashboard\?/);
    await page.reload();
    await page.getByRole("button", { name: "Step table", exact: true }).click();
    await expect(page.getByRole("row").filter({ has: page.getByRole("cell", { name: "Forecast", exact: true }) })).toContainText("8.00");
    const visual = (await (await request.get(`${root}/visualizations`)).json()).items[0];
    const result = await (await request.post(`${api}/api/v1/visualizations/${visual.id}/result`, { data: {} })).json();
    expect(result.rows.map((row: { balance: string }) => row.balance)).toEqual(["10.10", "10.30", "8.00", "8.00"]);
  } finally {
    const cleanup = await createRequest.newContext();
    expect((await cleanup.delete(`${root}?confirm=true`)).ok()).toBeTruthy(); await cleanup.dispose();
  }
});
