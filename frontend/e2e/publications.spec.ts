import { expect, test } from "@playwright/test";
import { readFileSync } from "node:fs";
import { resolve } from "node:path";

const api = process.env.NODEBI_E2E_API ?? "http://127.0.0.1:8000";
test("publish prepared data through UI and create an independent chart, copy and restore dashboard", async ({ page, request }) => {
  test.setTimeout(120000);
  const project = await (await request.post(`${api}/api/v1/projects`, { data: { name: "Published chart acceptance" } })).json();
  try {
    await request.post(`${api}/api/v1/projects/${project.id}/sources/excel`, { multipart: { file: { name: "sales.xlsx", mimeType: "application/vnd.openxmlformats-officedocument.spreadsheetml.sheet", buffer: readFileSync(resolve("../fixtures/excel/sales.xlsx")) } } });
    await page.goto(`/projects/${project.id}/workflow`);
    await page.getByRole("button", { name: "New field workflow", exact: true }).click();
    const saved = async () => { await expect(page.getByText("Saved", { exact: true })).toBeVisible(); await expect(page.getByText("Updating fields", { exact: true })).toHaveCount(0); };
    await page.getByTitle("Add Excel Source", { exact: true }).click(); await saved();
    await page.getByText("Published results and filters", { exact: true }).click();
    await page.getByLabel("Result name", { exact: true }).fill("Sales records");
    const options = page.getByLabel("Result output", { exact: true }).locator("option");
    await expect(options).toHaveCount(2);
    await page.getByLabel("Result output", { exact: true }).selectOption({ index: 1 });
    await page.getByRole("button", { name: "Publish result", exact: true }).click(); await saved();
    const workflowId = new URL(page.url()).searchParams.get("workflow");
    const graphPath = `${api}/api/v1/workflows/${workflowId}`;
    const graph = await (await request.get(graphPath)).json();
    expect(graph.version).toBe(3);
    expect(graph.result_catalog.outputs).toHaveLength(1);
    await page.goto(`/projects/${project.id}/visualizations`);
    await page.getByRole("button", { name: "Create visualization", exact: true }).click();
    const dialog = page.getByRole("dialog", { name: "Independent visualization", exact: true });
    await dialog.getByLabel("Visualization name", { exact: true }).fill("Sales table");
    await dialog.getByLabel("Visualization type", { exact: true }).selectOption("table");
    await dialog.getByRole("button", { name: "Preview visualization", exact: true }).click();
    await expect(dialog.locator("table")).toBeVisible();
    await dialog.getByRole("button", { name: "Save visualization", exact: true }).click();
    await expect(dialog).toHaveCount(0);
    await expect(page.getByText("Sales table · Table", { exact: true })).toBeVisible();
    expect((await (await request.get(`${api}/api/v1/projects/${project.id}/dashboards`)).json()).items).toHaveLength(0);
    await page.goto(`/projects/${project.id}/dashboard`);
    await page.getByRole("button", { name: "Create dashboard", exact: true }).click();
    await page.getByText("Sales table · Table", { exact: true }).locator("..").getByRole("button", { name: "Add widget", exact: true }).click();
    await expect(page.locator("[data-widget-id] table")).toBeVisible();
    await page.getByRole("button", { name: "Save dashboard", exact: true }).click(); await saved();
    expect(await (await request.get(graphPath)).json()).toEqual(graph);
    const widget = page.locator("[data-widget-id]");
    await widget.getByRole("button", { name: "Independent visualization copy", exact: true }).click();
    await dialog.getByLabel("Visualization name", { exact: true }).fill("Independent sales table");
    await dialog.getByRole("button", { name: "Save visualization", exact: true }).click();
    await expect(dialog).toHaveCount(0);
    await page.getByRole("button", { name: "Save dashboard", exact: true }).click(); await saved();
    const visuals = await (await request.get(`${api}/api/v1/projects/${project.id}/visualizations`)).json();
    expect(visuals.items).toHaveLength(2);
    expect(visuals.items.every((item: { publication_id: string }) => item.publication_id === graph.result_catalog.outputs[0].id)).toBe(true);
    await page.reload(); await expect(page.locator("[data-widget-id] table")).toBeVisible();
    await page.getByLabel("Show shared period", { exact: true }).check();
    await page.getByRole("button", { name: "Save dashboard", exact: true }).click(); await saved();
    await page.getByLabel("Start date", { exact: true }).fill("2026-01-01");
    await page.getByLabel("End date", { exact: true }).fill("2026-01-31");
    await page.getByRole("button", { name: "Apply period", exact: true }).click();
    await expect(page).toHaveURL(/period=/);
    await expect(widget.getByText("Period is not connected to this visualization.")).toBeVisible();
    await page.reload(); await expect(page.getByLabel("Start date", { exact: true })).toHaveValue("2026-01-01");
    expect(await (await request.get(graphPath)).json()).toEqual(graph);
  } finally { await request.delete(`${api}/api/v1/projects/${project.id}?confirm=true`); }
});
