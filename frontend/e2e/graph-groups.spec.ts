import { expect, test } from "@playwright/test";
import { readFileSync } from "node:fs";
import { resolve } from "node:path";
const api = process.env.NODEBI_E2E_API ?? "http://127.0.0.1:8000";

for (const selection of ["canvas", "checkboxes"]) test(`group nodes (${selection}), preserve boundary connections and restore view preferences without graph saves`, async ({ page, request }) => {
  test.setTimeout(90000);
  const project = await (await request.post(`${api}/api/v1/projects`, { data: { name: "Groups acceptance" } })).json();
  try {
    const workflow = await (await request.post(`${api}/api/v1/projects/${project.id}/workflows`, { data: { name: "Grouped workflow" } })).json();
    const upload = await request.post(`${api}/api/v1/projects/${project.id}/sources/excel`, { multipart: { file: { name: "sales.xlsx", mimeType: "application/vnd.openxmlformats-officedocument.spreadsheetml.sheet", buffer: readFileSync(resolve("../fixtures/excel/sales.xlsx")) } } });
    expect(upload.ok()).toBe(true); const source = await upload.json();
    const ids = Array.from({ length: 4 }, () => crypto.randomUUID());
    const definitions = [{ type: "excel_source", config: { source_id: source.id, sheet_name: source.workbook.sheets[0].name } }, { type: "calculated_column", config: { name: "Double quantity", expression: "quantity * 2" } }, { type: "limit", config: { limit: 10 } }, { type: "limit", config: { limit: 5 } }];
    const nodes = ids.map((id, index) => ({ id, ...definitions[index], version: 1, position: { x: Math.min(index, 2) * 300, y: index === 3 ? 230 : 0 }, ui: {} }));
    const edges = [[0, 1], [1, 2], [0, 3]].map(([source, target]) => ({ id: crypto.randomUUID(), source_node_id: ids[source], source_port: "dataset", target_node_id: ids[target], target_port: "input" }));
    expect((await request.put(`${api}/api/v1/workflows/${workflow.id}`, { data: { name: workflow.name, nodes, edges, parameters: [], expected_revision: workflow.revision } })).ok()).toBe(true);
    const read = async () => (await request.get(`${api}/api/v1/workflows/${workflow.id}`)).json();
    const preview = async () => { const result = await request.post(`${api}/api/v1/workflows/${workflow.id}/nodes/${ids[2]}/preview`, { data: { limit: 100 } }); expect(result.ok(), await result.text()).toBe(true); return result.json(); };
    const baseline = await preview();
    const saved = () => expect(page.getByText("Saved", { exact: true })).toBeVisible();
    if (selection === "checkboxes") await page.setViewportSize({ width: 420, height: 900 });
    await page.goto(`/projects/${project.id}/workflow`);
    await page.getByLabel("Edit workflow node").selectOption(ids[0]);
    if (selection === "canvas") {
      await page.locator(`.react-flow__node[data-id="${ids[0]}"]`).click();
      await page.locator(`.react-flow__node[data-id="${ids[1]}"]`).click({ modifiers: ["Shift"] });
      await page.getByText("Node groups", { exact: true }).click();
    } else {
      await page.getByText("Node groups", { exact: true }).click();
      const beforeSelection = await read();
      await page.getByRole("button", { name: "Clear selection", exact: true }).click();
      await expect(page.getByText(/Selected nodes: 0/)).toBeVisible();
      const choices = page.getByRole("region", { name: "Nodes for grouping", exact: true }).getByRole("checkbox");
      await choices.nth(0).focus();
      await page.keyboard.press("Space");
      await page.keyboard.press("Tab");
      await expect(choices.nth(1)).toBeFocused();
      await page.keyboard.press("Space");
      await expect(choices.nth(0)).toBeChecked();
      await expect(choices.nth(1)).toBeChecked();
      await expect.poll(() => page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
      await page.screenshot({ path: test.info().outputPath("checkbox-selection.png"), fullPage: true });
      expect(await read()).toEqual(beforeSelection);
    }
    await expect(page.getByText(/Selected nodes: 2/)).toBeVisible();
    await page.getByLabel("Group name", { exact: true }).fill("Preparation");
    await page.getByRole("button", { name: "Group selected nodes", exact: true }).click(); await saved();
    const grouped = await read();
    expect(grouped.nodes.filter((node: { ui: { group?: string } }) => node.ui.group === "Preparation")).toHaveLength(2);
    expect(grouped.edges).toHaveLength(3);
    expect((await preview()).rows).toEqual(baseline.rows);
    await page.getByLabel("Toggle group Preparation", { exact: true }).click();
    await expect(page.getByTestId("collapsed-group")).toHaveCount(1);
    await expect(page.locator(".react-flow__node")).toHaveCount(3);
    await expect(page.locator(".react-flow__edge")).toHaveCount(2);
    await page.getByText("Editor panels", { exact: true }).click();
    await page.getByLabel("Configuration panel width", { exact: true }).focus();
    await page.getByLabel("Configuration panel width", { exact: true }).press("End");
    await expect(page.getByLabel("Configuration panel width", { exact: true })).toHaveValue("640");
    const widthControl = page.getByLabel("Configuration panel width", { exact: true });
    const widthBox = (await widthControl.boundingBox())!;
    await widthControl.click({ position: { x: widthBox.width / 2, y: widthBox.height / 2 } });
    expect(Number(await widthControl.inputValue())).toBeGreaterThan(260);
    expect(Number(await widthControl.inputValue())).toBeLessThan(640);
    expect(await read()).toEqual(grouped);
    await widthControl.press("End");
    await expect(widthControl).toHaveValue("640");
    await page.getByRole("button", { name: "Fit view", exact: true }).click();
    await page.screenshot({ path: test.info().outputPath("groups.png") });
    expect(await read()).toEqual(grouped);
    await page.reload();
    await expect(page.getByTestId("collapsed-group")).toHaveCount(1);
    await page.getByText("Editor panels", { exact: true }).click();
    await expect(page.getByLabel("Configuration panel width", { exact: true })).toHaveValue("640");
    expect(await read()).toEqual(grouped);
    await page.getByLabel("Edit workflow node").selectOption(ids[0]);
    await expect(page.getByTestId("collapsed-group")).toHaveCount(0);
    await expect(page.locator(`.react-flow__node[data-id="${ids[0]}"]`)).toBeInViewport();
    await page.getByText("Node groups", { exact: true }).click();
    await page.getByLabel("Active group", { exact: true }).selectOption("Preparation");
    await page.getByRole("list", { name: "Group members" }).getByRole("button", { name: /Double quantity/ }).click();
    await expect(page.getByLabel("Edit workflow node")).toHaveValue(ids[1]);
    await page.getByLabel("Group name", { exact: true }).fill("Renamed preparation");
    await page.getByRole("button", { name: "Rename group", exact: true }).click(); await saved();
    expect((await read()).nodes.filter((node: { ui: { group?: string } }) => node.ui.group === "Renamed preparation")).toHaveLength(2);
    await page.getByRole("button", { name: "Undo graph change", exact: true }).click(); await saved();
    expect((await read()).nodes.filter((node: { ui: { group?: string } }) => node.ui.group === "Preparation")).toHaveLength(2);
    await page.getByLabel("Active group", { exact: true }).selectOption("Preparation");
    await page.getByRole("button", { name: "Dissolve group", exact: true }).click(); await saved();
    const dissolved = await read();
    expect(dissolved.nodes).toHaveLength(4);
    expect(dissolved.nodes.every((node: { ui: { group?: string } }) => !node.ui.group)).toBe(true);
    expect(dissolved.edges).toEqual(grouped.edges);
    const output = await preview(); expect(output.rows).toEqual(baseline.rows); expect(output.columns).toEqual(baseline.columns);
  } finally { await request.delete(`${api}/api/v1/projects/${project.id}?confirm=true`); }
});
