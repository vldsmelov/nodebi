import { expect, test } from "@playwright/test";
import { configureFormLayout, expectDialogFits, formLayouts } from "./form-reflow";
import { readFileSync } from "node:fs";
import { resolve } from "node:path";
const api = process.env.NODEBI_E2E_API ?? "http://127.0.0.1:8000";
for (const layout of formLayouts) test(`create, undo, restore and edit dependent calculated fields as ordinary nodes (${layout})`, async ({ page, request }) => {
  test.setTimeout(90000);
  await configureFormLayout(page, layout);
  const project = await (await request.post(`${api}/api/v1/projects`, { data: { name: "Calculated table" } })).json();
  try {
    const workflow = await (await request.post(`${api}/api/v1/projects/${project.id}/workflows`, { data: { name: "Table" } })).json();
    const source = await (await request.post(`${api}/api/v1/projects/${project.id}/sources/excel`, { multipart: { file: { name: "sales.xlsx", mimeType: "application/vnd.openxmlformats-officedocument.spreadsheetml.sheet", buffer: readFileSync(resolve("../fixtures/excel/sales.xlsx")) } } })).json();
    const sourceId = crypto.randomUUID();
    expect((await request.put(`${api}/api/v1/workflows/${workflow.id}`, { data: { name: workflow.name, expected_revision: workflow.revision, nodes: [{ id: sourceId, type: "excel_source", version: 1, position: { x: 0, y: 0 }, ui: {}, config: { source_id: source.id, sheet_name: source.workbook.sheets[0].name } }], edges: [], parameters: [] } })).ok()).toBe(true);
    const read = async () => (await request.get(`${api}/api/v1/workflows/${workflow.id}`)).json();
    await page.goto(`/projects/${project.id}/workflow`);
    await page.getByLabel("Edit workflow node").selectOption(sourceId);
    await page.getByRole("button", { name: "Add calculated fields", exact: true }).click();
    const dialog = page.getByRole("dialog", { name: "Calculated fields table" });
    await dialog.getByLabel("Calculated field name 1").fill("Gross");
    await dialog.getByLabel("Expression", { exact: true }).fill("quantity * price");
    const add = dialog.getByRole("button", { name: "Add calculated field", exact: true });
    await add.focus();
    await page.keyboard.press("Enter");
    await expect(dialog.getByLabel("Calculated field name 2")).toBeFocused();
    await dialog.getByLabel("Calculated field name 2").fill("Net");
    await dialog.getByLabel("Insert formula field").nth(1).selectOption({ label: "Gross · unknown" });
    const netExpression = await dialog.getByLabel("Expression", { exact: true }).nth(1).inputValue();
    await dialog.getByLabel("Expression", { exact: true }).nth(1).fill(`${netExpression} * 0.8`);
    const before = await read(); expect(before.nodes).toHaveLength(1);
    await dialog.getByRole("button", { name: "Move up", exact: true }).nth(1).focus();
    await page.keyboard.press("Enter");
    await expect(dialog.getByLabel("Calculated field name 1")).toBeFocused();
    await expect(dialog.getByLabel("Calculated field name 1")).toHaveValue("Net");
    await expect(dialog.getByRole("button", { name: "Apply calculated fields" })).toBeDisabled();
    await dialog.getByRole("button", { name: "Move down", exact: true }).first().focus();
    await page.keyboard.press("Enter");
    await expect(dialog.getByLabel("Calculated field name 2")).toBeFocused();
    await add.focus();
    await page.keyboard.press("Enter");
    await expect(dialog.getByLabel("Calculated field name 3")).toBeFocused();
    await dialog.getByRole("button", { name: "Remove", exact: true }).nth(2).focus();
    await page.keyboard.press("Enter");
    await expect(dialog.getByLabel("Calculated field name 2")).toBeFocused();
    await page.screenshot({ path: "../.backups/ux-calculated-table.png" });
    await dialog.getByRole("button", { name: "Apply calculated fields" }).click();
    await expect(dialog).toHaveCount(0); await expect(page.getByText("Saved", { exact: true })).toBeVisible();
    const created = await read(); expect(created.nodes).toHaveLength(3); expect(created.edges).toHaveLength(2);
    expect(created.nodes.filter((node: { type: string }) => node.type === "calculated_column")).toHaveLength(2);
    expect(created.revision).toBe(before.revision + 1);
    await page.getByRole("button", { name: "Preview output", exact: true }).click();
    await expect(page.getByRole("table").getByRole("row").nth(1).getByRole("cell").last()).toHaveText("128");
    await page.getByRole("button", { name: "Undo graph change", exact: true }).click();
    await expect(page.getByText("Saved", { exact: true })).toBeVisible(); expect((await read()).nodes).toHaveLength(1);
    await page.getByRole("button", { name: "Redo graph change", exact: true }).click();
    await expect(page.getByText("Saved", { exact: true })).toBeVisible();
    await page.reload();
    const gross = created.nodes.find((node: { config: { name?: string } }) => node.config.name === "Gross");
    await page.getByLabel("Edit workflow node").selectOption(gross.id);
    await page.getByRole("button", { name: "Edit calculated chain", exact: true }).click();
    await expect(dialog.getByLabel("Calculated field name 2")).toHaveValue("Net");
    await dialog.getByLabel("Expression", { exact: true }).first().fill("quantity * price * 2");
    await expectDialogFits(page, dialog);
    await page.screenshot({ path: test.info().outputPath("calculated-table.png") });
    await dialog.getByRole("button", { name: "Apply calculated fields" }).click();
    await expect(page.getByText("Saved", { exact: true })).toBeVisible();
    const edited = await read(); expect(edited.edges).toEqual(created.edges);
    expect(edited.nodes.map((node: { id: string }) => node.id).sort()).toEqual(created.nodes.map((node: { id: string }) => node.id).sort());
    await page.getByRole("button", { name: "Edit calculated chain", exact: true }).click();
    await expect(dialog.getByLabel("Expression", { exact: true }).first()).toHaveValue("quantity * price * 2");
    await dialog.getByLabel("Calculated field name 1").fill("Discarded");
    page.once("dialog", prompt => prompt.accept());
    await dialog.getByRole("button", { name: "Cancel", exact: true }).click(); expect(await read()).toEqual(edited);
    const net = created.nodes.find((node: { config: { name?: string } }) => node.config.name === "Net");
    await page.getByLabel("Edit workflow node").selectOption(net.id);
    await page.getByRole("button", { name: "Preview output", exact: true }).click();
    await expect(page.getByRole("table").getByRole("row").nth(1).getByRole("cell").last()).toHaveText("256");
    await page.getByLabel("Edit workflow node").selectOption(gross.id);
    await page.getByLabel("Expression", { exact: true }).fill("quantity * price * 3");
    await expect(page.getByText("Saved", { exact: true })).toBeVisible();
    await page.getByRole("button", { name: "Edit calculated chain", exact: true }).click();
    await expect(dialog.getByLabel("Expression", { exact: true }).first()).toHaveValue("quantity * price * 3");
    await dialog.getByRole("button", { name: "Cancel", exact: true }).click();
  } finally { await request.delete(`${api}/api/v1/projects/${project.id}?confirm=true`); }
});
